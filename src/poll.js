const calc = (label = '', skipVoters = []) => {
  const result = [];
  for (const [name, arr] of Object.entries(books)) {
    const grades = [];
    for (const a of arr) {
      for (let i = 0; i < a.length; i++) {
        if (a[i] === 0 || skipVoters.includes(i)) {
          continue;
        }
        grades.push(a[i]);
      }
    }
    const avg = grades.reduce((a, b) => a + b, 0) / grades.length;
    result.push([name, avg]);
  }

  result.sort((a, b) => b[1] - a[1]);
  console.log('\x1b[90m' + label + ':\x1b[0m');
  result.forEach(([name, avg]) => console.log(name.padEnd(17, '.'), +avg.toFixed(3)));
  console.log();
};

